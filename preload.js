const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  start: (title) => ipcRenderer.invoke('rec:start', title),
  chunk: (buf) => ipcRenderer.send('rec:chunk', buf),
  stop: () => ipcRenderer.invoke('rec:stop'),
  transcribe: (id) => ipcRenderer.invoke('transcribe', id),
  createMom: (id) => ipcRenderer.invoke('mom:create', id),
  copyMom: (id) => ipcRenderer.invoke('mom:copy', id),
  exportMomPdf: (id) => ipcRenderer.invoke('mom:pdf', id),
  list: () => ipcRenderer.invoke('list'),
  read: (id) => ipcRenderer.invoke('read', id),
  reveal: () => ipcRenderer.invoke('reveal'),
  prepareMedia: () => ipcRenderer.invoke('media:prepare'),
  openPrivacySettings: (kind) => ipcRenderer.invoke('media:settings', kind),
  openMeeting: (link) => ipcRenderer.invoke('meeting:open', link),
  onMeetingStart: (cb) => ipcRenderer.on('meeting:start', (_e, info) => cb(info)),
  getCalendar: () => ipcRenderer.invoke('calendar:get'),
  setCalendar: (url) => ipcRenderer.invoke('calendar:set', url),
  onStatus: (cb) => ipcRenderer.on('status', (_e, msg) => cb(msg)),
  onMeetingEnd: (cb) => ipcRenderer.on('meeting:end', () => cb()),
  isMicMuted: () => ipcRenderer.invoke('mic:muted'),
  onMicMuted: (cb) => ipcRenderer.on('mic:muted', (_e, muted) => cb(muted)),
  onBotState: (cb) => ipcRenderer.on('bot:state', (_e, state) => cb(state)),
  captureBot: () => ipcRenderer.invoke('bot:capture'),
  botSignIn: () => ipcRenderer.invoke('bot:signin'),
  getAi: () => ipcRenderer.invoke('ai:get'),
  setAi: (settings) => ipcRenderer.invoke('ai:set', settings),
});
